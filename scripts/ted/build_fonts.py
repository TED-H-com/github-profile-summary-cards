#!/usr/bin/env python3
"""Build the font subsets that the Ted dashboard embeds in every SVG.

GitHub serves README images through a proxy that blocks external font requests,
so the cards carry their own fonts as base64 woff2. Each face keeps only the
characters the cards can show, which keeps an SVG small:

  Ted Inter 400/500        printable ASCII, a few spaces, the middle dot and the ellipsis
  Ted Inter Display 500    digits and number punctuation, for the large figures
  Ted Noto TC 400/500      the CJK characters found in src/ted/i18n.ts

Only kerning and tabular figures survive as OpenType features.

The subsets are renamed so no Reserved Font Name ('Source', from Noto Sans TC's
Source Han Sans origin) appears in a modified font, as the SIL OFL 1.1 requires.

Usage:
  pip install fonttools brotli
  python scripts/ted/build_fonts.py --inter <Inter-4.1 unzip dir> --noto <NotoSansTC-wght.ttf>
  npx prettier --write src/ted/fonts.generated.ts

Inter 4.1: https://github.com/rsms/inter/releases (extras/ttf)
Noto Sans TC: https://github.com/google/fonts/tree/main/ofl/notosanstc
"""

import argparse
import base64
import io
import json
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parents[2]
I18N = ROOT / 'src' / 'ted' / 'i18n.ts'
OUT = ROOT / 'src' / 'ted' / 'fonts.generated.ts'

SPACES = '\u00a0\u2009\u202f'  # no-break, thin and narrow no-break spaces
TEXT_CHARS = ''.join(chr(c) for c in range(0x20, 0x7F)) + SPACES + '\u00b7\u2026'  # middle dot, ellipsis
FIGURE_CHARS = '0123456789,.%+- ' + SPACES


def cjk_chars():
    """Every character in i18n.ts outside ASCII and Latin-1: the zh-TW strings."""
    text = I18N.read_text('utf-8')
    return ''.join(sorted({ch for ch in text if ord(ch) > 0x2FFF}))


def rename(font, family, style):
    """Give the subset its own name; drop the typographic family records."""
    table = font['name']
    for name_id in (16, 17, 21, 22, 25):
        table.removeNames(nameID=name_id)
    postscript = family.replace(' ', '') + '-' + style.replace(' ', '')
    for name_id, value in ((1, family), (2, 'Regular'), (3, postscript), (4, family + ' ' + style), (6, postscript)):
        table.setName(value, name_id, 3, 1, 0x409)
        table.setName(value, name_id, 1, 0, 0)


def advance_widths(font, chars):
    """Advance width of each character in em, for layout-time text measurement."""
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    upm = font['head'].unitsPerEm
    return {ch: round(hmtx[cmap[ord(ch)]][0] / upm, 4) for ch in chars if ord(ch) in cmap}


def build(font, chars):
    options = subset.Options()
    options.layout_features = ['kern', 'tnum']
    options.hinting = False
    options.desubroutinize = True
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6]
    options.name_languages = [0x409]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[ord(ch) for ch in chars])
    subsetter.subset(font)
    font.flavor = 'woff2'
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--inter', required=True, type=pathlib.Path, help='unzipped Inter-4.1 directory')
    parser.add_argument('--noto', required=True, type=pathlib.Path, help='NotoSansTC variable font (wght axis)')
    args = parser.parse_args()

    ttf = args.inter / 'extras' / 'ttf'
    cjk = cjk_chars()
    faces = []
    metrics = {}

    for weight, style, source in ((400, 'Regular', 'Inter-Regular.ttf'), (500, 'Medium', 'Inter-Medium.ttf')):
        font = TTFont(ttf / source)
        metrics[f'text-{weight}'] = advance_widths(font, TEXT_CHARS)
        rename(font, 'Ted Inter', style)
        faces.append(('Ted Inter', weight, build(font, TEXT_CHARS)))

    font = TTFont(ttf / 'InterDisplay-Medium.ttf')
    metrics['figure-500'] = advance_widths(font, FIGURE_CHARS)
    rename(font, 'Ted Inter Display', 'Medium')
    faces.append(('Ted Inter Display', 500, build(font, FIGURE_CHARS)))

    for weight, style in ((400, 'Regular'), (500, 'Medium')):
        font = instancer.instantiateVariableFont(TTFont(args.noto), {'wght': weight})
        rename(font, 'Ted Noto TC', style)
        faces.append(('Ted Noto TC', weight, build(font, cjk)))

    lines = [
        '// Generated by scripts/ted/build_fonts.py from Inter 4.1 and Noto Sans TC (SIL OFL 1.1,',
        '// see fonts/). Do not edit by hand.',
        '',
        'export interface FontFace {',
        '    family: string;',
        '    weight: number;',
        '    woff2: string;',
        '}',
        '',
        'export const FONT_FACES: FontFace[] = [',
    ]
    for family, weight, data in faces:
        encoded = base64.b64encode(data).decode('ascii')
        lines.append(f"    {{family: '{family}', weight: {weight}, woff2: '{encoded}'}},")
    lines.append('];')
    lines.append('')
    lines.append('// Advance widths in em, keyed by face and then character.')
    lines.append('export const ADVANCES: {[face: string]: {[char: string]: number}} = ' + json.dumps(metrics, ensure_ascii=False) + ';')
    lines.append('')
    OUT.write_text('\n'.join(lines), 'utf-8')

    for family, weight, data in faces:
        print(f'{family} {weight}: {len(data):,} bytes woff2')
    print(f'CJK characters: {len(cjk)} ({cjk})')
    print(f'Wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
